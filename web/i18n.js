export function getLang(){
  try{const v=localStorage.getItem('continuumLang');if(v==='en'||v==='es')return v}catch{}
  return 'es';
}

export function storeLang(l){
  try{localStorage.setItem('continuumLang',l)}catch{}
}

let current=getLang();

export function lang(){return current}

export function useLang(l){
  current=(l==='en'||l==='es')?l:'es';
  storeLang(current);
  return current;
}

export function t(key,vars){
  let s=(I18N[current]||{})[key];
  if(s==null)s=(I18N.en||{})[key];
  if(s==null)return key;
  if(vars)for(const k in vars)s=String(s).split('{'+k+'}').join(String(vars[k]));
  return s;
}
